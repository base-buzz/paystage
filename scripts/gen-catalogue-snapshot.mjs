#!/usr/bin/env node
/**
 * Copy the newest supply-catalogue reading into the repository.
 *
 * `/lists` needs a denominator — the payees the catalogue lists — and the catalogue is an ops-side measurement
 * (`/work/ops/docs/state/supply/<date>.json`), not a file the console can read at build time. This script writes
 * the few fields the page needs into `apps/console/src/lib/catalogue.json`; `scripts/gen-lists-manifest.mjs`
 * then reads that file, so the denominator on the page is generated rather than typed.
 *
 *   node scripts/gen-catalogue-snapshot.mjs
 *   PAYSTAGE_SUPPLY_DIR=/some/dir node scripts/gen-catalogue-snapshot.mjs
 *
 * Only the counts and the date are copied, not the multi-megabyte item list: the page needs a denominator, not
 * the catalogue itself.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DIR = process.env.PAYSTAGE_SUPPLY_DIR ?? "/work/ops/docs/state/supply";
const OUT = join(ROOT, "apps/console/src/lib/catalogue.json");

const files = readdirSync(DIR)
  .filter((name) => /^\d{4}-\d{2}-\d{2}\.json$/.test(name))
  .sort();
if (files.length === 0) {
  console.error(`catalogue-snapshot: no dated snapshots in ${DIR}`);
  process.exit(1);
}

const snapshotName = files[files.length - 1];
const snapshot = JSON.parse(readFileSync(join(DIR, snapshotName), "utf8"));
const payees = Number(snapshot.payees);
if (!Number.isInteger(payees) || payees <= 0) {
  console.error(`catalogue-snapshot: ${snapshotName} has no positive integer payees count`);
  process.exit(1);
}

const body = {
  note: "Generated by scripts/gen-catalogue-snapshot.mjs from the newest ops supply snapshot — do not edit.",
  snapshot: snapshotName,
  measuredAt: snapshot.measured_at ?? null,
  source: snapshot.source ?? null,
  payees,
  rows: Number.isFinite(Number(snapshot.rows)) ? Number(snapshot.rows) : null,
  totalAdvertised: Number.isFinite(Number(snapshot.total_advertised)) ? Number(snapshot.total_advertised) : null,
};

writeFileSync(OUT, `${JSON.stringify(body, null, 2)}\n`);
console.log(`catalogue-snapshot: wrote ${OUT} — ${payees} payees from ${snapshotName}`);
