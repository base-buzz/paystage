#!/usr/bin/env node
/**
 * Generate the positive payee registry the evaluator can use offline (#133 → #164).
 *
 * The negative list says "never pay these". This is the opposite fact: for a host we have actually probed, this is the payee it
 * publishes. A 402 from that host naming a different address is either a legitimate rotation or an endpoint claiming a host it
 * does not control — and today nothing can tell the difference, which is exactly the gap four of five tested agents asked about.
 *
 * Source of truth is `registry/services.json` — the same file `/lists` renders and `verify-registry.mjs` re-probes, so the map
 * cannot drift from what we published. Every entry carries the date it was verified.
 *
 *   node scripts/gen-verified-payees.mjs          # write
 *   node scripts/gen-verified-payees.mjs --check  # exit 1 when stale (runs in CI)
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "registry/services.json");
const OUT = join(ROOT, "packages/preflight/src/verified-payees.ts");

const services = JSON.parse(readFileSync(SOURCE, "utf8"));
const entries = [];
for (const svc of services) {
  if (!svc.url || !svc.payTo) continue;
  let host;
  try {
    host = new URL(svc.url).host.toLowerCase();
  } catch {
    continue;
  }
  entries.push({ host, service: svc.name, payee: svc.payTo.toLowerCase(), verified_at: svc.verified_at ?? null });
}
entries.sort((a, b) => a.host.localeCompare(b.host));

const body = `/**
 * Host → payee, for hosts whose 402 challenge we have actually probed. Generated by scripts/gen-verified-payees.mjs from
 * registry/services.json — do not edit.
 *
 * What this is for: a challenge states \`resource\` and \`payTo\`, and nothing ties them together. An endpoint can claim any host in
 * its resource field and ask to be paid at its own address. When a host appears here with a different payee, the evaluator
 * returns \`review\` instead of \`pay\` — not \`do_not_pay\`, because a provider can legitimately rotate its payee and refusing on
 * rotation would punish the honest case the registry exists to protect.
 */
export interface VerifiedPayee {
  host: string;
  service: string;
  payee: string;
  verified_at: string | null;
}

export const VERIFIED_PAYEES: readonly VerifiedPayee[] = ${JSON.stringify(entries, null, 2)} as const;

const BY_HOST = new Map(VERIFIED_PAYEES.map((e) => [e.host, e]));

/** The verified record for a host, or undefined when we have never probed it. */
export function verifiedPayeeFor(host: string | undefined | null): VerifiedPayee | undefined {
  if (typeof host !== "string" || host.length === 0) return undefined;
  return BY_HOST.get(host.toLowerCase());
}
`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== body) {
    console.error("verified-payees: out of date — run node scripts/gen-verified-payees.mjs");
    process.exit(1);
  }
  console.log(`verified-payees: current (${entries.length} host(s))`);
  process.exit(0);
}

writeFileSync(OUT, body);
console.log(`verified-payees: wrote ${entries.length} host(s) → ${OUT}`);
