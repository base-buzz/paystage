#!/usr/bin/env node
/**
 * Bake the commit into the bundle, because a Worker cannot read the environment that built it.
 *
 * `/api/build` first tried to publish `process.env.PAYSTAGE_BUILD_SHA` at request time and returned null from CI: the variable exists
 * when the bundle is built and not when it runs, which is the difference between build-time and run-time that keeps catching people
 * out. Writing a tiny generated module moves the value into the source, where the bundler cannot lose it.
 *
 *   node scripts/gen-build-info.mjs            # write from CI env, falling back to git and then to "unknown"
 *   node scripts/gen-build-info.mjs --check    # fail if the file is missing or malformed
 */
import { execFileSync } from "node:child_process";
import { writeFileSync, existsSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "apps/console/src/lib/build-info.generated.ts");

const sha =
  process.env.PAYSTAGE_BUILD_SHA ??
  process.env.GITHUB_SHA ??
  (() => {
    try {
      return execFileSync("git", ["rev-parse", "HEAD"], { cwd: ROOT, encoding: "utf8" }).trim();
    } catch {
      return "unknown";
    }
  })();

const builtAt = process.env.PAYSTAGE_BUILD_AT ?? new Date().toISOString();
const source = process.env.CI ? "ci" : "local";

const body = `/**
 * Generated by scripts/gen-build-info.mjs — do not edit.
 *
 * What commit built this deployment. Read by /api/build so a green deploy of the wrong commit is visible.
 */
export const BUILD_INFO = ${JSON.stringify({ sha, built_at: builtAt, source }, null, 2)} as const;
`;

if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || !/export const BUILD_INFO/.test(readFileSync(OUT, "utf8"))) {
    console.error("build-info: missing or malformed — run node scripts/gen-build-info.mjs");
    process.exit(1);
  }
  console.log("build-info: present");
  process.exit(0);
}

writeFileSync(OUT, body);
console.log(`build-info: ${sha.slice(0, 8)} (${source})`);
