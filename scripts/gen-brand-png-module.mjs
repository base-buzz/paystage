#!/usr/bin/env node
/**
 * Embed the tier PNG exports in the VouchGuard Worker.
 *
 * The brand pack is assembled at request time, but `sharp` is a build tool: it cannot run in a
 * Cloudflare Worker and should not be a runtime dependency of the site. So the tier rasters that
 * `scripts/brand-kit.mjs` renders from `scripts/lib/mark.mjs` are embedded here as base64, and the
 * zip route composes them with SVG masters drawn live at request time. The bytes still come from
 * the same module; `scripts/check-brand-assets.mjs` hashes every embedded file against `brand/`, so
 * a stale copy is red on the same run that regenerates the kit.
 *
 *   node scripts/gen-brand-png-module.mjs          # write the module
 *   node scripts/gen-brand-png-module.mjs --check  # exit 1 if the committed module is stale
 *
 * Node stdlib only: no dependency, no network.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { PACK_PNG_NAMES, PACK_VERSION_DATE } from "./lib/brand-pack.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const BRAND = join(ROOT, "brand");
const OUT = join(ROOT, "apps/vouchguard/src/lib/brand-pngs.generated.mjs");
const check = process.argv.includes("--check");

const missing = PACK_PNG_NAMES.filter((name) => !existsSync(join(BRAND, name)));
if (missing.length > 0) {
  console.error(`gen-brand-png-module: missing brand/${missing.join(", ")} — run \`npm run brand:rebuild\` first`);
  process.exit(1);
}

const data = {};
const hashes = {};
for (const name of PACK_PNG_NAMES) {
  const bytes = readFileSync(join(BRAND, name));
  data[name] = bytes.toString("base64");
  hashes[name] = createHash("sha256").update(bytes).digest("hex");
}

const body = `/**
 * Generated by scripts/gen-brand-png-module.mjs — do not edit.
 *
 * The tier PNGs the pack serves, embedded so the route works in a Worker with no filesystem and
 * no sharp. Source: brand/${PACK_PNG_NAMES[0]} and its siblings, rendered from scripts/lib/mark.mjs.
 * Spec version ${PACK_VERSION_DATE}; scripts/check-brand-assets.mjs fails if these bytes drift.
 */
export const BRAND_PNG_VERSION = ${JSON.stringify(PACK_VERSION_DATE)};

/** @type {Readonly<Record<string, string>>} base64 PNG bytes */
export const BRAND_PNGS = Object.freeze(${JSON.stringify(data, null, 2)});

/** @type {Readonly<Record<string, string>>} sha256 of each decoded PNG */
export const BRAND_PNG_SHA256 = Object.freeze(${JSON.stringify(hashes, null, 2)});
`;

if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== body) {
    console.error("gen-brand-png-module: apps/vouchguard/src/lib/brand-pngs.generated.mjs is stale");
    console.error("  run `node scripts/gen-brand-png-module.mjs` and commit the result");
    process.exit(1);
  }
  console.log(`gen-brand-png-module: ${PACK_PNG_NAMES.length} embedded PNG(s) match brand/`);
  process.exit(0);
}

writeFileSync(OUT, body);
const total = Object.values(data).reduce((sum, value) => sum + value.length, 0);
console.log(
  `gen-brand-png-module: embedded ${PACK_PNG_NAMES.length} PNG(s), ${total} base64 bytes -> apps/vouchguard/src/lib/brand-pngs.generated.mjs`,
);
