#!/usr/bin/env node
/**
 * Generate the provenance table for the two documents that carry the safety claims.
 *
 *   node scripts/gen-provenance-table.mjs          # write PROVENANCE.md
 *   node scripts/gen-provenance-table.mjs --check  # exit 1 when the table is stale
 *
 * The table lives in its own page because neither source file can carry its own sha256: hashing
 * SECURITY.md after writing its hash into SECURITY.md is a fixed-point problem, not a formatting
 * choice. So the page lists both files, and the two source files link to it.
 *
 * `mtime` is the file's modification time at generation. Git does not preserve mtimes across clones,
 * so the check compares size and sha256 (which change when the content changes) and treats mtime as
 * recorded context, not a CI assertion. Comparing mtime would fail every clean checkout.
 */
import { createHash } from "node:crypto";
import { readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "PROVENANCE.md");

export const FILES = ["SECURITY.md", "packages/preflight/KNOWN_DRAINERS.md"];

export function provenanceRows(root = ROOT) {
  return FILES.map((file) => {
    const path = join(root, file);
    const bytes = readFileSync(path);
    return {
      file,
      size: bytes.length,
      mtime: statSync(path).mtime.toISOString().replace(/\.\d{3}Z$/, "Z"),
      sha256: createHash("sha256").update(bytes).digest("hex"),
    };
  });
}

export function renderProvenanceTable(root = ROOT) {
  const rows = provenanceRows(root)
    .map(
      (row) =>
        `| [\`${row.file}\`](${row.file}) | ${row.size} | ${row.mtime} | \`${row.sha256}\` |`,
    )
    .join("\n");

  return `# Provenance — the files the safety claims rest on

Generated by \`node scripts/gen-provenance-table.mjs\` — do not edit by hand. \`node
scripts/check-provenance-table.mjs\` fails CI when a size or sha256 here no longer matches the file.

The two source files cannot carry their own hash without hashing the line that contains the hash, so
the table lives here and each file links to it. \`mtime\` is recorded when the table is generated;
git does not preserve mtimes across clones, so CI verifies size and sha256, which change whenever the
content does.

| File | Size (bytes) | mtime (UTC) | sha256 |
| --- | ---: | --- | --- |
${rows}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, renderProvenanceTable());
  console.log(`provenance: wrote ${FILES.length} rows to PROVENANCE.md`);
}
