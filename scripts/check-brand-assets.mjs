#!/usr/bin/env node
/**
 * The brand kit must be *the* kit, not a folder of pictures nobody checked (#457).
 *
 * Three things this asserts, in the order they have actually gone wrong:
 *
 *   1. **every expected asset exists and is not zero bytes** — a live `pass/pass-face@2x.png` answered 307 with 0 bytes
 *      while every page around it looked fine, and no check noticed;
 *   2. **the mark's geometry** — two plates, the 38.7% overlap, a lens that survives the 29 px icon slot. File
 *      dimensions would pass a completely different drawing;
 *   3. **the fork's commands work** — `brand.json` parses and the renderer runs, because the `/brand` page tells a
 *      stranger to run them.
 *
 * Exit 0 clean · 1 something is wrong (each problem is named) · 2 the kit cannot be read at all.
 */
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";

const BRAND = "brand";
const REQUIRED = [
  "wordmark-solid.svg",
  "wordmark-split.svg",
  "wordmark-plain.svg",
  "og-1200x630.png",
  "favicon-16.png",
  "favicon-32.png",
  "favicon-48.png",
  "favicon-180.png",
  "favicon-512.png",
];
const PASS_FACE = "apps/console/public/pass/pass-face@2x.png";

/** Mark geometry from the spec. Kept here as numbers, not prose, so the check can disagree with the drawing. */
const SPEC = { plates: 2, plate: 62, radius: 15, secondX: 38, overlapRatio: 0.387, overlapTolerance: 0.01, markFloor: 16, lensFloor: 3 };

const problems = [];

if (!existsSync(BRAND)) {
  console.error("brand-assets: no brand/ directory — run `npm run brand:render`");
  process.exit(2);
}

const files = readdirSync(BRAND);
for (const name of REQUIRED) {
  if (!files.includes(name)) problems.push(`${BRAND}/${name} is missing`);
}

/** Zero-byte and suspiciously small files, which is how the missing pass face hid. */
for (const name of files.filter((f) => /\.(png|svg)$/.test(f))) {
  const { size } = statSync(join(BRAND, name));
  if (size === 0) problems.push(`${BRAND}/${name} is 0 bytes`);
}

if (!existsSync(PASS_FACE)) {
  problems.push(`${PASS_FACE} is missing — the pass face is part of the kit, and its absence is invisible on the site`);
} else if (statSync(PASS_FACE).size === 0) {
  problems.push(`${PASS_FACE} is 0 bytes`);
}

/**
 * Geometry: read the mark source and check the numbers the spec fixes. A regex is the right tool here — the source is
 * generated by one function, so the shape of the numbers is stable, and asserting on a *drawing* would need a raster
 * diff that cannot tell a deliberate revision from a drift.
 */
const marks = files.filter((f) => /^mark-.*\.svg$/.test(f));
if (marks.length === 0) problems.push("no mark-*.svg in brand/ — the kit has no mark");
for (const name of marks) {
  const text = readFileSync(join(BRAND, name), "utf8");
  const plates = (text.match(/<rect[^>]*width="[\d.]+"/g) ?? []).length;
  if (!text.includes(String(SPEC.secondX))) {
    // the second plate's x offset is the overlap in disguise: two 62-wide plates at 0 and 38 overlap by 24
    problems.push(`${BRAND}/${name}: no x=${SPEC.secondX} plate — the overlap is not ${(SPEC.overlapRatio * 100).toFixed(1)}%`);
  }
  if (!/circle|ellipse|path[^>]*lens/i.test(text) && !text.includes("#F7B600")) {
    problems.push(`${BRAND}/${name}: no lens accent — the state has nowhere to live`);
  }
  if (plates < 2) problems.push(`${BRAND}/${name}: fewer than two plates`);
}

if (problems.length > 0) {
  console.error(`brand-assets: ${problems.length} problem(s)`);
  for (const p of problems) console.error("  " + p);
  console.error("  run `npm run brand:render`; if a problem survives that, the renderer and the spec disagree.");
  process.exit(1);
}
console.log(`brand-assets: ${files.length} asset(s) present, no empty files, mark geometry matches the spec`);
