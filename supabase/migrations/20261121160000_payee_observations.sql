-- Payee observations (#310): the rows behind `GET /wallets/<address>`.
--
-- Each row is one named source's observation of one field at one time. They are deliberately not
-- collapsed into a per-address summary: a score or a single "trust" value would be a judgement this
-- product cannot defend, and two sources that disagree must both survive. The classifier in
-- packages/policy/src/payee-category.ts reads these rows and returns labels, observations and
-- disagreements; it never fetches anything itself.
--
-- Read path is SERVER ONLY, like probe_runs: RLS is enabled with no policy. The service role reads
-- through apps/hosted/src/payee-observation-store.ts, and the public route exposes one address at a
-- time. No listing endpoint exists.
--
-- Collecting the observations (RPC code/nonce, first-seen source, holdings, GoPlus) is a recorded
-- follow-up and is NOT done by this migration or by the route. Until a collector writes rows, the
-- route correctly returns an empty observation list for every address.
--
-- Apply this migration through the repo's normal migration path; nothing here is hand-applied, and
-- no credentials live in this file.

create table if not exists public.payee_observations (
  id bigint generated by default as identity primary key,
  -- Canonical lowercase EVM address. The collector normalises; the read route queries lowercase.
  address text not null check (address ~ '^0x[0-9a-f]{40}$'),
  -- Which source said it. Non-empty by construction: an observation with no named source is not a fact.
  source text not null check (length(btrim(source)) > 0),
  -- When the source was read, not when the address was created.
  observed_at timestamptz not null,
  -- The fields the classifier recognises. A new field is a classifier change, not a loose string.
  field text not null check (
    field in (
      'code',
      'first_seen',
      'nonce',
      'tx_count',
      'holds_asset',
      'sanctions',
      'drainer',
      'non_receivable',
      'goplus'
    )
  ),
  -- The observed value in the shape that field defines. JSON because these are different facts
  -- (boolean, integer, date string, {asset, holds}, list hit, GoPlus flag) and merging them into one
  -- number is exactly what this table exists to avoid.
  value jsonb not null,
  created_at timestamptz not null default now()
);

-- The read is "all rows for one address, oldest first". The source/field order makes the response
-- deterministic even when several rows share a timestamp.
create index if not exists payee_observations_address_observed_idx
  on public.payee_observations (address, observed_at asc, source asc, field asc);

alter table public.payee_observations enable row level security;

comment on table public.payee_observations is
  'Per-source payee observations (#310). Server-side only: RLS enabled, no anon policy. No aggregate score column exists by design.';
