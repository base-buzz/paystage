import type { Metadata } from "next";
import "../landing.css";
import backlog from "@/lib/backlog.generated.json";

/**
 * The backlog — public, unlisted, and deliberately not linked from anywhere yet.
 *
 * Two reasons for the shape:
 *
 *  - **Unlisted, not secret.** It sits at a normal path but no page, sitemap, `llms.txt` or route document names it,
 *    and `robots` says `noindex` so a crawler that arrives anyway does not file it. Anyone with the URL can read it;
 *    nobody is told the URL. That is the difference between "unpublished" and "hidden", and only the first is honest.
 *  - **A summary per entry, not the body.** Each row carries the claim, the condition that closes it, what gates it and
 *    the evidence line for a finished item. The working notes underneath — guesses, operator waits, rejected drafts —
 *    stay in the queue. `ops/bin/backlog-export.mjs` redacts credential-shaped strings and counts what it redacted.
 *
 * The data file is generated by `ops/bin/backlog-export.mjs`. If it is stale the page says so rather than looking
 * current — a backlog page that quietly shows last week's list is worse than one that admits the date.
 */
export const metadata: Metadata = {
  title: "Backlog",
  description: "What is open and what is done, as a list.",
  robots: { index: false, follow: false, nocache: true },
};

const DATE = new Intl.DateTimeFormat("en-NZ", { dateStyle: "medium", timeStyle: "short", timeZone: "Pacific/Auckland" });

export default function BacklogPage() {
  const generated = new Date(backlog.generatedAt);
  const ageDays = (Date.now() - generated.getTime()) / 86_400_000;
  const items = [...backlog.items].sort((a, b) => Number(a.done) - Number(b.done) || a.n - b.n);
  const open = items.filter((i) => !i.done);
  const done = items.filter((i) => i.done);

  return (
    <main className="lp-wrap lp-prose">
      <h1>Backlog</h1>
      <p className="lp-lead">
        {backlog.counts.open} open, {backlog.counts.done} done — {backlog.counts.total} entries, published from the queue
        the work is actually planned in. This page is not linked from anywhere: it exists because the queue is real, not
        because it is a feature.
      </p>

      <p className="lp-note">
        Generated {DATE.format(generated)} from <code>{backlog.source}</code>
        {ageDays > 2 ? ` — ${Math.floor(ageDays)} days old, so treat the counts as history rather than status` : ""}. Each
        row is the claim, the condition that closes it, and what gates it; the working notes stay in the queue.
        {backlog.redactedFields > 0
          ? ` ${backlog.redactedFields} field${backlog.redactedFields === 1 ? " was" : "s were"} redacted before publishing.`
          : ""}
      </p>

      <h2>Open ({open.length})</h2>
      <ul className="lp-backlog">
        {open.map((item) => (
          <li key={item.n} id={`n${item.n}`}>
            <span className="lp-backlog-title">
              {item.n}. {item.title}
            </span>
            {item.size ? <span className="lp-note"> · {item.size}</span> : null}
            {item.summary ? <p className="lp-note">{item.summary}</p> : null}
            {item.doneWhen ? (
              <p className="lp-note">
                <strong>done when:</strong> {item.doneWhen}
              </p>
            ) : null}
            {item.gate ? (
              <p className="lp-note">
                <strong>gate:</strong> {item.gate}
              </p>
            ) : null}
          </li>
        ))}
      </ul>

      <h2>Done ({done.length})</h2>
      <details>
        <summary className="lp-note">Show the {done.length} finished entries, newest first</summary>
        <ul className="lp-backlog">
          {[...done].reverse().map((item) => (
            <li key={item.n} id={`n${item.n}`}>
              <span className="lp-backlog-title">
                {item.n}. {item.title}
              </span>
              {item.size ? <span className="lp-note"> · {item.size}</span> : null}
              {item.ref ? <span className="lp-note"> — {item.ref}</span> : null}
              {item.summary ? <p className="lp-note">{item.summary}</p> : null}
            </li>
          ))}
        </ul>
      </details>
    </main>
  );
}
